def main() -> int:
    parser = argparse.ArgumentParser(description="Generate kaitencloud's models from the contract.")
    parser.add_argument(
        "--check", action="store_true", help="fail when the committed models are stale"
    )
    args = parser.parse_args()

    coverage = load(COVERAGE)
    core = load(CORE_SPEC)
    platform = load(PLATFORM_SPEC)

    core_source, core_names, core_exports = core_module(
        core, excluded=set(coverage["core"]["excluded"] or {})
    )
    platform_source, platform_exports = platform_module(
        platform, core, core_names, excluded=set(coverage["platform"]["excluded"] or {})
    )
    files = {
        TYPES / "__init__.py": types_package(core_exports, platform_exports),
        TYPES / "_core.py": core_source,
        TYPES / "_platform.py": platform_source,
        TYPES / "_webhooks.py": webhooks_module(core, core_names),
    }

    if emit(files, check=args.check):
        return 0
    if args.check:
        print("the generated models are stale: run `task generate`", file=sys.stderr)
        return 1
    return 0


def core_module(
    spec: dict[str, Any], *, excluded: set[str]
) -> tuple[str, dict[str, str], list[str]]:
    schemas = spec["components"]["schemas"]
    roots = response_roots(spec, excluded) | refs_in(spec.get("webhooks") or {})
    emitted = sorted(name for name in closure(schemas, roots) if not PAGE.match(name))
    names = {name: CLASS_NAMES.get(name, name) for name in emitted}

    module = ModelModule(source="openapi/openapi.yaml", schemas=schemas, names=names)
    # A subclass is defined after the class it extends.
    for name in sorted(emitted, key=lambda name: (name in EXTENDS, names[name])):
        module.add_schema(name)
    module.enums["Scope"] = scopes(spec)
    return module.render(), names, module.exports


def scopes(spec: dict[str, Any]) -> tuple[str, ...]:
    """Every scope an organization credential can carry, as the contract publishes them."""
    published = {
        scope
        for scheme in (spec.get("components", {}).get("securitySchemes") or {}).values()
        for scope in scheme.get("x-kaiten-scopes") or ()
    }
    if not published:
        raise SystemExit("the contract publishes no x-kaiten-scopes: Scope would be empty")
    return tuple(sorted(published))


def platform_module(
    spec: dict[str, Any],
    core: dict[str, Any],
    core_names: dict[str, str],
    *,
    excluded: set[str],
) -> tuple[str, list[str]]:
    schemas = spec["components"]["schemas"]
    core_schemas = core["components"]["schemas"]

    names: dict[str, str] = {}
    own: list[str] = []
    for name in sorted(closure(schemas, response_roots(spec, excluded))):
        if name in core_names and without_prose(schemas[name]) == without_prose(core_schemas[name]):
            # The same shape under the same name: one Python class serves both surfaces.
            names[name] = core_names[name]
            continue
        python = CLASS_NAMES.get(name, name)
        if python in core_names.values():
            python = f"Platform{python}"
        names[name] = python
        own.append(name)

    module = ModelModule(source="openapi/platform-openapi.yaml", schemas=schemas, names=names)
    module.imports = {python for name, python in names.items() if name not in own}
    for name in own:
        module.add_schema(name)
    return module.render(), module.exports


def types_package(core_exports: list[str], platform_exports: list[str]) -> str:
    """``kaitencloud.types``: every generated model, and the hand-written ``*Param`` shapes."""
    groups = (
        ("_core", core_exports),
        ("_params", params_exports()),
        ("_platform", platform_exports),
    )
    lines = [
        HEADER.format(source="the snapshots in openapi/"),
        '"""Models and parameter types for the Kaiten API.',
        "",
        "The models are generated from the API contract. The ``*Param`` typed dictionaries describe",
        "the nested values the client methods accept.",
        '"""',
        "",
    ]
    for module, names in groups:
        lines += [f"from .{module} import (", *(f"    {name}," for name in names), ")"]
    everything = sorted({name for _, names in groups for name in names})
    lines += ["", "__all__ = [", *(f"    {json.dumps(name)}," for name in everything), "]", ""]
    return "\n".join(lines)


def params_exports() -> list[str]:
    """The literal ``__all__`` of the hand-written ``_params.py``, read without importing it."""
    tree = ast.parse(PARAMS.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__all__" for target in node.targets
        ):
            return sorted(ast.literal_eval(node.value))
    raise SystemExit(f"{PARAMS.relative_to(ROOT)} has no literal __all__")


def webhooks_module(spec: dict[str, Any], core_names: dict[str, str]) -> str:
    lines = [
        HEADER.format(source="openapi/openapi.yaml"),
        '"""The events Kaiten delivers to webhook endpoints, one model per published contract."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Annotated, Literal",
        "",
        "from pydantic import Field",
        "",
        "from .._models import KaitenModel",
    ]

    events: list[tuple[str, str, str, str, str]] = []
    headers: set[str] = set()
    for key, item in sorted((spec.get("webhooks") or {}).items()):
        operation = item["post"]
        schema = operation["requestBody"]["content"]["application/json"]["schema"]
        properties = schema["properties"]
        unknown = set(properties) - {"name", "type", "data", "headers"}
        if unknown:
            raise SystemExit(f"webhook {key}: the envelope has unsupported properties {unknown}")
        # Every envelope carries the same headers, or none does: one rule renders them all.
        headers.add(
            core_names[ref_name(properties["headers"]["$ref"])] if "headers" in properties else ""
        )
        event_type = only_enum_value(properties["type"], f"webhook {key}.type")
        if event_type != key:
            raise SystemExit(f"webhook {key}: its type enum says {event_type!r}")
        event_name = only_enum_value(properties["name"], f"webhook {key}.name")
        data = core_names[ref_name(properties["data"]["$ref"])]
        python = re.sub(r"^on", "", operation["operationId"]) + "Event"
        summary = operation.get("description") or operation.get("summary") or ""
        events.append((python, event_name, event_type, data, summary))

    if len(headers) > 1:
        raise SystemExit(f"webhooks: the envelopes disagree on their headers: {sorted(headers)}")
    header = next(iter(headers), "")
    data_types = sorted({data for _, _, _, data, _ in events} | ({header} - {""}))
    lines.append(f"from ._core import {', '.join(data_types)}")
    lines += ["", "__all__ = [", '    "WEBHOOK_EVENTS",', '    "WebhookEvent",']
    lines += [f'    "{python}",' for python, *_ in sorted(events)]
    lines += ["]", ""]

    for python, event_name, event_type, data, summary in events:
        lines += ["", f"class {python}(KaitenModel):"]
        lines += docstring(f"{summary} Delivered as ``{event_type}``.", "    ")
        lines += [
            "",
            f"    name: Literal[{json.dumps(event_name)}]",
            '    """The event name."""',
            "",
            f"    type: Literal[{json.dumps(event_type)}]",
            '    """The event type: what tells one event from another."""',
            "",
            f"    data: {data}",
            '    """What the event is about."""',
            "",
        ]
        if header:
            lines += [
                f"    headers: {header} | None = None",
                '    """The trace context of the request that produced the event."""',
                "",
            ]

    members = "\n".join(f"    | {python}" for python, *_ in events).lstrip(" |")
    lines += [
        "",
        f'WebhookEvent = Annotated[\n    {members},\n    Field(discriminator="type"),\n]',
        '"""Any event Kaiten delivers to a webhook endpoint, discriminated by ``type``."""',
        "",
        "WEBHOOK_EVENTS: dict[str, type[KaitenModel]] = {",
        *(f"    {json.dumps(event_type)}: {python}," for python, _, event_type, _, _ in events),
        "}",
        '"""Every published event type, mapped to the model that parses it."""',
        "",
    ]
    return "\n".join(lines)


class ModelModule:
    """Renders the models of one contract document into one Python module."""

    def __init__(self, *, source: str, schemas: dict[str, Any], names: dict[str, str]) -> None:
        self.source = source
        self.schemas = schemas
        self.names = names
        self.imports: set[str] = set()
        self.enums: dict[str, tuple[Any, ...]] = {}
        self.unions: dict[str, tuple[str | None, list[str]]] = {}
        self.aliases: dict[str, str] = {}
        self.nullable_aliases: set[str] = set()
        self.classes: list[str] = []
        self.body: list[str] = []

    @property
    def exports(self) -> list[str]:
        return sorted({*self.enums, *self.unions, *self.aliases, *self.classes})

    def add_schema(self, name: str) -> None:
        schema = self.schemas[name]
        python = self.names[name]
        if "properties" in schema or schema.get("type") == "object":
            self.classes.append(python)
            self.body += ["", *self.render_class(name, schema), ""]
        elif "oneOf" in schema or "anyOf" in schema:
            self.union(schema, owner=name, name=python)
        else:
            annotation = self.annotation(schema, owner=name, prop=None)
            self.aliases[python] = annotation
            if annotation.endswith("| None"):
                self.nullable_aliases.add(python)

    def render_class(self, name: str, schema: dict[str, Any]) -> list[str]:
        python = self.names[name]
        base = EXTENDS.get(name)
        lines = [f"class {python}({self.names[base] if base else 'KaitenModel'}):"]
        lines += docstring(schema.get("description") or CLASS_DOCS.get(python), "    ")

        required = set(schema.get("required") or [])
        properties: dict[str, Any] = schema.get("properties") or {}
        inherited = self.inherited(name, base) if base else set()
        if not set(properties) - inherited and len(lines) == 1:
            lines.append("    pass")

        for wire, node in properties.items():
            if wire in inherited:
                continue
            attribute = FIELD_NAMES.get((name, wire), snake_case(wire))
            if keyword.iskeyword(attribute) or hasattr(BaseModel, attribute):
                raise SystemExit(
                    f"{name}.{wire}: {attribute!r} would shadow a pydantic member; "
                    "give it a name in FIELD_NAMES"
                )

            annotation = self.annotation(node, owner=name, prop=wire)
            if wire in required:
                default = f" = Field(alias={json.dumps(wire)})" if attribute != wire else ""
            else:
                if not self.is_nullable(annotation):
                    annotation += " | None"
                default = (
                    f" = Field(default=None, alias={json.dumps(wire)})"
                    if attribute != wire
                    else " = None"
                )

            lines += ["", f"    {attribute}: {annotation}{default}"]
            lines += docstring(node.get("description"), "    ")
        return lines

    def inherited(self, name: str, base: str) -> set[str]:
        """The properties ``name`` takes from ``base`` as they are, checking it really extends it.

        Each property of the base must keep its type in the derived schema -- rendered as the
        base's, so their enums get the base's names -- and stay required where the base requires
        it. A property the base has and the derived schema lacks must be optional in the base.
        """
        own = self.schemas[name].get("properties") or {}
        parent = self.schemas[base]
        required = set(self.schemas[name].get("required") or [])
        for wire, node in (parent.get("properties") or {}).items():
            where = f"{name}.{wire}"
            if wire not in own:
                if wire in (parent.get("required") or []):
                    raise SystemExit(f"{where}: missing, but required by {base}, which it extends")
                continue
            if wire in (parent.get("required") or []) and wire not in required:
                raise SystemExit(f"{where}: optional, but required by {base}, which it extends")
            ours = self.annotation(own[wire], owner=base, prop=wire)
            theirs = self.annotation(node, owner=base, prop=wire)
            if ours != theirs:
                raise SystemExit(f"{where}: {ours}, but {theirs} in {base}, which it extends")
        return set(own) & set(parent.get("properties") or {})

    def annotation(self, node: dict[str, Any], *, owner: str, prop: str | None) -> str:
        where = f"{owner}.{prop}" if prop else owner
        if "$ref" in node:
            return self.names[ref_name(node["$ref"])]
        for key in ("oneOf", "anyOf"):
            if key in node:
                return self.union(node, owner=owner)

        kind = node.get("type")
        nullable = False
        if isinstance(kind, list):
            nullable = "null" in kind
            rest = [item for item in kind if item != "null"]
            if len(rest) > 1:
                raise SystemExit(f"{where}: multi-type schemas are not supported ({kind})")
            kind = rest[0] if rest else None

        if kind is None:
            text = "Any"
        elif kind == "string":
            text = self.string(node, owner=owner, prop=prop)
        elif kind == "integer":
            text = "int"
        elif kind == "number":
            text = "float"
        elif kind == "boolean":
            text = "bool"
        elif kind == "array":
            text = f"list[{self.annotation(node.get('items') or {}, owner=owner, prop=prop)}]"
        elif kind == "object":
            if node.get("properties"):
                raise SystemExit(f"{where}: inline object schemas are not supported")
            extra = node.get("additionalProperties")
            value = (
                self.annotation(extra, owner=owner, prop=prop)
                if isinstance(extra, dict) and extra
                else "Any"
            )
            text = f"dict[str, {value}]"
        else:
            raise SystemExit(f"{where}: unsupported schema type {kind!r}")
        return f"{text} | None" if nullable else text

    def string(self, node: dict[str, Any], *, owner: str, prop: str | None) -> str:
        # A nullable enum lists null among its values; its type already says it is nullable.
        values = [value for value in node.get("enum") or [] if value is not None]
        if values:
            if len(values) == 1:
                return f"Literal[{json.dumps(values[0])}]"
            name = ENUM_NAMES.get((owner, prop or "")) or ENUM_VOCABULARY.get(
                (prop or "", frozenset(values))
            )
            if name is None:
                raise SystemExit(
                    f"{owner}.{prop}: name this enum in ENUM_NAMES or ENUM_VOCABULARY ({values})"
                )
            known = self.enums.setdefault(name, tuple(values))
            if set(known) != set(values):
                raise SystemExit(f"{name}: {owner}.{prop} has {values}, elsewhere {list(known)}")
            return f"{name} | str"
        if node.get("format") == "date-time":
            return "datetime"
        return "str"

    def union(self, node: dict[str, Any], *, owner: str, name: str | None = None) -> str:
        key = "oneOf" if "oneOf" in node else "anyOf"
        members: list[str] = []
        scalars: list[dict[str, Any]] = []
        nullable = False
        for member in node[key]:
            if member.get("type") == "null":
                # A null member makes the union nullable: `X | None`, not a model of its own.
                nullable = True
            elif "$ref" in member:
                members.append(ref_name(member["$ref"]))
            elif member.get("type") in ("boolean", "number", "integer", "string", "object") and (
                not member.get("properties") and not member.get("enum")
            ):
                scalars.append(member)
            else:
                raise SystemExit(f"{owner}: inline union members are not supported")

        if scalars:
            if members or name:
                raise SystemExit(f"{owner}: a union mixes inline values and schemas")
            text = " | ".join(self.annotation(member, owner=owner, prop=None) for member in scalars)
        elif len(members) == 1 and name is None:
            text = self.names[members[0]]
        else:
            name = name or UNION_NAMES.get(frozenset(members))
            if name is None:
                raise SystemExit(f"{owner}: name the union of {members} in UNION_NAMES")
            tag = (node.get("discriminator") or {}).get("propertyName") or self.shared_tag(members)
            self.unions[name] = (tag, [self.names[member] for member in members])
            text = name
        return f"{text} | None" if nullable else text

    def shared_tag(self, members: Iterable[str]) -> str | None:
        """``type``, when every member pins it to its own single value."""
        tags = []
        for member in members:
            enum = (self.schemas[member].get("properties") or {}).get("type", {}).get("enum") or []
            if len(enum) != 1:
                return None
            tags.append(enum[0])
        return "type" if len(set(tags)) == len(tags) else None

    def is_nullable(self, annotation: str) -> bool:
        return annotation.endswith("| None") or annotation in self.nullable_aliases

    def render(self) -> str:
        lines = [
            HEADER.format(source=self.source),
            "from __future__ import annotations",
            "",
            "from datetime import datetime",
            "from typing import Annotated, Any, Literal",
            "",
            "from pydantic import Field",
            "",
            "from .._models import KaitenModel",
        ]
        if self.imports:
            lines.append(f"from ._core import {', '.join(sorted(self.imports))}")
        lines += [
            "",
            "__all__ = [",
            *(f"    {json.dumps(name)}," for name in self.exports),
            "]",
            "",
        ]

        for name, values in sorted(self.enums.items()):
            lines += ["", f"{name} = Literal[{', '.join(json.dumps(value) for value in values)}]"]
            lines += docstring(ALIAS_DOCS.get(name), "")
        lines += self.body

        for name, (tag, members) in sorted(self.unions.items()):
            union = " | ".join(members)
            if tag:
                lines += [
                    "",
                    f"{name} = Annotated[{union}, Field(discriminator={json.dumps(tag)})]",
                ]
            else:
                lines += ["", f"{name} = {union}"]
            lines += docstring(ALIAS_DOCS.get(name), "")
        for name, annotation in sorted(self.aliases.items()):
            lines += ["", f"{name} = {annotation}"]
            lines += docstring(ALIAS_DOCS.get(name), "")

        if self.classes:
            # Annotations are strings under `from __future__ import annotations`, and some name
            # aliases defined after the classes. Resolving them here, once, makes a broken
            # model an import-time error instead of a surprise on the first response it parses.
            lines += ["", "", f"for _model in ({', '.join(self.classes)},):"]
            lines += ["    _model.model_rebuild()", "del _model", ""]
        return "\n".join(lines) + "\n"


def load(path: Path) -> Any:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def refs_in(node: Any) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str):
            found.add(ref_name(ref))
        for value in node.values():
            found |= refs_in(value)
    elif isinstance(node, list):
        for value in node:
            found |= refs_in(value)
    return found


def operations(spec: dict[str, Any]) -> Iterator[dict[str, Any]]:
    for item in spec["paths"].values():
        for method in HTTP_METHODS:
            if method in item:
                yield item[method]


def response_roots(spec: dict[str, Any], excluded: set[str]) -> set[str]:
    roots: set[str] = set()
    for operation in operations(spec):
        if operation["operationId"] in excluded:
            continue
        for response in (operation.get("responses") or {}).values():
            for media in (response.get("content") or {}).values():
                roots |= refs_in(media.get("schema") or {})
    return roots


def closure(schemas: dict[str, Any], roots: Iterable[str]) -> set[str]:
    seen: set[str] = set()
    pending = list(roots)
    while pending:
        name = pending.pop()
        if name not in seen:
            seen.add(name)
            pending.extend(refs_in(schemas[name]) - seen)
    return seen


def without_prose(node: Any) -> Any:
    """The schema minus its documentation, to tell whether two schemas describe one shape."""
    if isinstance(node, dict):
        return {key: without_prose(value) for key, value in node.items() if key not in PROSE}
    if isinstance(node, list):
        return [without_prose(value) for value in node]
    return node


def only_enum_value(node: dict[str, Any], where: str) -> str:
    values = node.get("enum") or []
    if len(values) != 1:
        raise SystemExit(f"{where}: expected a single-value enum, got {values}")
    return str(values[0])


def snake_case(name: str) -> str:
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return name.replace("-", "_").lower()


def docstring(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    text = " ".join(text.split()).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if text.endswith('"'):
        text += " "
    if len(indent) + len(text) + 6 <= 100:
        return [f'{indent}"""{text}"""']
    wrapped = textwrap.wrap(text, width=92 - len(indent))
    return [
        f'{indent}"""{wrapped[0]}',
        *(f"{indent}{line}" for line in wrapped[1:]),
        f'{indent}"""',
    ]


